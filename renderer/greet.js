let currentTitle = '';
let currentTip = '';

function titlePool(firstRun, now) {
  const m = now.getMonth() + 1, d = now.getDate(), day = now.getDay(), hr = now.getHours();
  const date = TITLES.dates[m + '-' + d];
  if (date) return date;
  if (firstRun) return TITLES.first;
  let ctx = [];
  if (hr >= 23 || hr < 5) ctx = TITLES.night;
  else if (day === 0 || day === 6) ctx = TITLES.weekend;
  else if (day === 5 && hr >= 17) ctx = TITLES.friday;
  else if (day === 1 && hr < 12) ctx = TITLES.monday;
  else if (hr < 11) ctx = TITLES.morning;
  else if (hr >= 17) ctx = TITLES.evening;
  return TITLES.any.concat(ctx, ctx);
}

function pickRandom(list, not) {
  if (list.length < 2) return list[0] || '';
  let x;
  do x = list[Math.floor(Math.random() * list.length)]; while (x === not);
  return x;
}

/** Новый случайный заголовок (не такой же, как прошлый). */
function rerollTitle(firstRun, now) {
  currentTitle = pickRandom(titlePool(!!firstRun, now || new Date()), currentTitle);
  return currentTitle;
}

function rerollTip() {
  currentTip = pickRandom(TIPS, currentTip);
  return currentTip;
}

